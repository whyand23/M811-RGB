// getting dpi packet from a level on spec mode (read-only)
// all index should be -1
const packet *get_dpi_packet(int mode, int level)
{
    if(mode < 0 || mode > MODES_COUNT) {
        return NULL;
    }
    if(level < 0 || level > MODES_COUNT) {
        return NULL;
    }

    return &dpi_packets[mode].dpi[level];
}

// setting specific bit(reading bits is reversed as it just an array)
// -1 every index needed
void set_dpi_packet(int mode, int level, unsigned char dpi_mod1, unsigned char dpi_mod2)
{
    if(mode < 0 || mode > MODES_COUNT) return;
    if(level < 0 || level > DPI_LEVELS) return;
    
    dpi_packets[mode].dpi[level][9] = dpi_mod1;
    dpi_packets[mode].dpi[level][10] = dpi_mod2;
    dpi_packets[mode].dpi[level][11] = dpi_mod1;
    dpi_packets[mode].dpi[level][12] = dpi_mod2;
}

