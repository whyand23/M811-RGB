command_t side_btn_sub[] = {
	{"key", side_btn_key, "Set Side Button to single key", NULL, 0}
};

static int set_side_btn_packet(int mode, int btn, mouse_config *temp)
{
    if(mode < 0 || mode > MODES_COUNT) return 0;
    if(btn < 0 || btn > 8) return 0;

    side_btn_packets[mode].btn[btn][8] = temp->buttons->mode;
    side_btn_packets[mode].btn[btn][9] = temp->buttons->mod1;
    side_btn_packets[mode].btn[btn][10] = temp->buttons->mod2;
    side_btn_packets[mode].btn[btn][11] = temp->buttons->mod3;

    return 1;
}

void side_btn_key(int argc, char **argv, int mode)
{
    printf("Changing mouse side button to a single key\n");
    if(argc <= 0) {
        fprintf(stderr, "No further command is given, can't proceed\n");
        return;
    }

    unsigned long side_btn = strtoul(argv[0], NULL, 10);
    if(side_btn > 8) {
        fprintf(stderr, "Side button should be 1-8\n");
        return;
    }

    // get current mode settings
    mouse_config temp_cfg = *get_mode_config(mode - 1);
	
	// getting key hash
    ht_t *key_table = key_hash();
    char *value = ht_get(key_table, argv[1]);
    if(!value)
    {
        fprintf(stderr, "Key Unrecgonized%s\n", argv[1]);
        return;
    }

	// register single key to temp struct
    temp_cfg.buttons[side_btn - 1].mode = 0x90;
    temp_cfg.buttons[side_btn - 1].mod1 = 0x0;
    temp_cfg.buttons[side_btn - 1].mod2 = (unsigned char)strtoul(value, NULL, 16);
	temp_cfg.buttons[side_btn - 1].mod3 = 0x0;

    free(key_table->entries);
    free(key_table);

	// writing changes in temp cfg to mouse config array
    set_mode_config(mode - 1, &temp_cfg);

    //saving changes to file
    mouse_config *all_mode = all_mode_configs();
    const char *cfgpath = "config.ini";
    if(!save_config(cfgpath , all_mode)) {
        fprintf(stderr, "Failed to save to %s\n", cfgpath);
    }

    // set changes to side btn packet
    if(!(set_side_btn_packet(mode - 1, side_btn - 1, &temp_cfg)))
    {
        fprintf(stderr, "Failed to set side btn packet\n");
    };

    // transfer to mouse
    if(transfer(side_btn_packets[mode - 1].btn[side_btn - 1]))
    {
        printf("Side button %lu is changed\n", side_btn);
    };

    return;
}
