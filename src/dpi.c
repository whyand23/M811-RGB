void dpi_main(int argc, char **argv, int mode) 
{
    printf("Changing mouse DPI\n");
    if(argc <= 0) {
        fprintf(stderr, "No further command is given, can't proceed\n");
        return;
    }

    if(strcmp(argv[0], "level") != 0 || argv[1] == NULL) 
    {
        fprintf(stderr, "Please input dpi level\n");
        return;
    }

    unsigned long dpi_level = strtoul(argv[1], NULL, 10);

    if(dpi_level < 0 || dpi_level > 5) {
        fprintf(stderr, "DPI level should be 1-5\n");
        return;
    }

    if (argv[2] == NULL)
    {
        fprintf(stderr, "Please input DPI\n");
        return;
    }

    ht_t *dpi_table = dpi_hash();

    char *value = ht_get(dpi_table, argv[2]);
    if (!value)
    {
        fprintf(stderr, "Wrong DPI seek help");
        return;
    }
    
    // get current mode settings
    mouse_config temp_cfg = *get_mode_config(mode - 1);

    // registering change to struct
    temp_cfg.dpi[dpi_level - 1] = (unsigned int)strtoul(argv[2], NULL, 10);

    //copying data changed in temp_cfg to mouse_config modes array
    set_mode_config(mode - 1, &temp_cfg);

    //saving changes to file
    mouse_config *all_mode = all_mode_configs();
    const char *cfgpath = "config.ini";
    if(!save_config(cfgpath , all_mode)) {
        fprintf(stderr, "Failed to save to %s\n", cfgpath);
    }

    char *end;
    long int mod1 = (unsigned char)strtol(value, &end, 16);
    long int mod2 = 0x0; // default multiplyer(none) for below 6000 dpi
    
    if(*end == ':') {
        value = end;
        value++;
        mod2 = (unsigned char)strtol(value, &end, 16);
    }


    set_dpi_packet(mode - 1, dpi_level - 1, mod1, mod2);
    
    if(transfer(dpi_packets[mode - 1].dpi[dpi_level - 1]))
    {
        printf("Mouse DPI Changed\n");
    }

    free(dpi_table->entries);
    free(dpi_table);
    return;
}